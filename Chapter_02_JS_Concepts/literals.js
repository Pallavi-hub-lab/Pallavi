let age = "John"; // String literal

let isStudent = true; // Boolean literal

let pi = 3.14; // Number literal

let name = 'Alice'; // String literal

let nullValue = null; // Null literal

let undefinedValue; // Undefined literal   - variable declared but not assigned a value


console.log(typeof age); // Output: string
console.log(typeof isStudent); // Output: boolean
console.log(typeof pi); // Output: number
console.log(typeof name);
console.log(typeof nullValue); // Output: object (this is a known quirk in JavaScript)
console.log(typeof undefinedValue); // Output: undefined    

